def province_market_price(name: str) -> dict | None:
    """按省份名（支持「广东省」等全称）取销地批发价。"""
    short = name
    for suffix in ("壮族自治区", "回族自治区", "维吾尔自治区", "特别行政区", "自治区", "省", "市"):
        if short.endswith(suffix):
            short = short[: -len(suffix)]
            break
    return PROVINCE_MARKET_PRICE.get(short)


def county_farm_price(name: str) -> dict | None:
    """按县区名取真实产地价，并换算为元/kg（1 斤 = 0.5 kg）。"""
    row = COUNTY_FARM_PRICE.get(name)
    if not row:
        return None
    return {
        "price": row["price"],
        "price_per_kg": round(row["price"] * 2, 2),
        "period": row["period"],
        "variety": row.get("variety"),
        "source": _COUNTY_PRICE_SOURCE,
    }


def county_pest_control(name: str) -> dict | None:
    return COUNTY_PEST_CONTROL.get(name)
